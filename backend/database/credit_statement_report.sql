-- ============================================================================
-- Customer credit statement - what a customer owes, and for how long
-- ============================================================================
--   mysql -u root -p ihealthpharm < backend/database/credit_statement_report.sql
--
-- A customer paying off credit could see what they had just paid (the receipt)
-- but never what they still owe, bill by bill, or how long they had owed it.
-- The existing statements come closest - CUSTOMER_STATEMENT_BY_MASTERACCOUNT
-- and OUTSTANDING_RECEIVABLES - but neither works out how long a bill has been
-- outstanding, neither shows what was actually bought, and both are A4 report
-- documents rather than something to hand across the counter.
--
-- One row per item, with the bill's figures repeated, so the generator can
-- group the items under their bill. Ordered oldest debt first, which is the
-- order the conversation with the customer goes in.
--
-- Which bills count is deliberately the same rule the settlement screen uses -
-- Sales Billing only, Pending or Partially Paid, something still to receive,
-- and not one of the stale rows whose bill carries no balance. A statement that
-- disagreed with the screen the money was taken on would be worse than none.
-- If ReceivableSql changes in the backend, this has to change with it.
-- ============================================================================

DROP PROCEDURE IF EXISTS `CUSTOMER_CREDIT_STATEMENT`;

DELIMITER $$
CREATE PROCEDURE `CUSTOMER_CREDIT_STATEMENT`(WHERECLAUSE VARCHAR(500))
BEGIN
DECLARE BASE_SQL VARCHAR(5000) DEFAULT '';

SET BASE_SQL = 'select ar.MASTER_ACC_NO, ar.CUSTOMER_NAME,
  coalesce(ar.BILL_NO, ar.SOURCE_REF) as BILL_CODE,
  date_format(coalesce(s1.BILL_DATE,s2.BILL_DATE,s3.BILL_DATE,ar.RECEIPT_DATE),"%d-%m-%y") as BILL_DATE,
  datediff(curdate(), coalesce(s1.BILL_DATE,s2.BILL_DATE,s3.BILL_DATE,ar.RECEIPT_DATE)) as DAYS_OWING,
  coalesce(s1.NET_AMOUNT,s2.NET_AMOUNT,s3.NET_AMOUNT) as BILL_TOTAL,
  coalesce(ar.AMOUNT_RECEIVED,0) as PAID,
  ar.AMOUNT_TO_BE_RECEIVED as OWING,
  coalesce(i.ITEM_NM,"") as ITEM_NM,
  coalesce(si.SALE_QTY,0) as SALE_QTY,
  ma.CREDIT_LIMIT, ma.CREDIT_LIMIT_LEFT
from account_receivables ar
left join sales s1 on s1.BILL_ID = ar.SALES_BILL_ID
left join sales s2 on s2.BILL_CODE = ar.BILL_NO
left join sales s3 on s3.BILL_CODE = ar.SOURCE_REF
left join sales_items si on si.BILL_ID = coalesce(s1.BILL_ID,s2.BILL_ID,s3.BILL_ID)
left join items i on i.ITEM_ID = si.ITEM_ID
left join master_account ma on ma.CREDIT_NUMBER = ar.MASTER_ACC_NO
where ar.SOURCE_TYPE = "Sales Billing"
  and ar.PAYMENT_STATUS in ("Pending","Partially Paid")
  and ar.AMOUNT_TO_BE_RECEIVED > 0
  and coalesce(ar.ACTIVE_S,"Y") = "Y"
  and (coalesce(s1.BILL_ID,s2.BILL_ID,s3.BILL_ID) is null
       or coalesce(s1.BALANCE_AMOUNT,s2.BALANCE_AMOUNT,s3.BALANCE_AMOUNT) > 0)';

-- The caller's filter arrives as " WHERE 1 = 1 AND ...", so its WHERE is
-- replaced with AND to graft it onto the conditions above.
SET @FINAL_SQL = CONCAT(BASE_SQL, ' AND ', SUBSTRING(WHERECLAUSE, 8),
                        ' order by DAYS_OWING desc, BILL_CODE, ITEM_NM');

PREPARE stmt FROM @FINAL_SQL;
EXECUTE stmt;
DEALLOCATE PREPARE stmt;

END$$
DELIMITER ;

-- ---------------------------------------------------------------------------
-- Register the report. Header and footer are copied from the receipt so the
-- statement carries the same letterhead and the customer recognises it as
-- coming from the same counter.
--
-- CUSTOMER_CREDIT_STATEMENT is generated by its own class rather than the
-- generic table printer: the items have to sit under the bill they belong to,
-- and a flat table repeating the bill's date and totals against every product
-- would be unreadable on a till roll.
-- ---------------------------------------------------------------------------
INSERT INTO `reports_mapping`
  (`REPORT_CODE`, `REPORT_NAME`, `STORED_PROCEDURE_NAME`, `INPUT_PARAMETERS`,
   `REPORT_TITLE`, `HEADER_CONTENT`, `FOOTER_CONTENT`,
   `SHOW_VERTICAL_LINES`, `SHOW_BAR_CHARTS`, `CUSTOM_REPORT_GENERATOR`)
SELECT 'CUSTOMER_CREDIT_STATEMENT',
       'CUSTOMER CREDIT STATEMENT',
       'CUSTOMER_CREDIT_STATEMENT(?)',
       '[{"fieldName":"ACCOUNT NO","columnName":"MASTER_ACC_NO","type":"String","operator":"EQ","alias":"ar."},{"fieldName":"CUSTOMER NAME","columnName":"CUSTOMER_NAME","type":"String","operator":"EQ","alias":"ar."}]',
       'STATEMENT OF ACCOUNT',
       r.HEADER_CONTENT, r.FOOTER_CONTENT,
       r.SHOW_VERTICAL_LINES, r.SHOW_BAR_CHARTS,
       'com.ihealthpharm.reports.helper.CustomerCreditStatementPdf'
FROM `reports_mapping` r
WHERE r.REPORT_CODE = 'ACCOUNT_RECEIVABLES_RECEIPT'
  AND NOT EXISTS (SELECT 1 FROM `reports_mapping` x WHERE x.REPORT_CODE = 'CUSTOMER_CREDIT_STATEMENT');
